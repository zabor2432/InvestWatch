#!/usr/bin/env python3
"""Generates THIRD_PARTY.md (libraries and tools with licences) from the lockfiles.

Python: production dependencies from each project's uv.lock, licence from the installed package metadata.
Frontend: production packages from package-lock.json (`license` field). Run: python3 scripts/third_party.py
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PY_PROJECTS = ["backend", "orchestrator", "demo/seed", "demo/collect", "scraper", "migrations"]
LICENSE_SCRIPT = """
import importlib.metadata as m, json, sys
names = set(sys.argv[1:])
out = {}
for d in m.distributions():
    n = d.metadata["Name"].lower().replace("_", "-")
    classifiers = [c.split("::")[-1].strip() for c in (d.metadata.get_all("Classifier") or []) if c.startswith("License ::")]
    out[n] = d.metadata.get("License-Expression") or (classifiers[0] if classifiers else None) or (d.metadata.get("License") or "")[:40] or "?"
print(json.dumps({k: v for k, v in out.items() if k in names}))
"""


def python_rows(project: str) -> list[tuple[str, str, str]]:
    export = subprocess.run(
        ["uv", "export", "--frozen", "--no-dev", "--no-hashes", "--no-emit-local"],
        cwd=ROOT / project, capture_output=True, text=True, check=True).stdout
    pins = dict(l.split(";")[0].strip().split("==") for l in export.splitlines() if "==" in l and not l.startswith("-e"))
    pins = {k.lower().replace("_", "-"): v for k, v in pins.items()}
    # licence metadata exists only for installed packages: use the project's environment (uv sync was run for dev)
    res = subprocess.run(["uv", "run", "--frozen", "python", "-c", LICENSE_SCRIPT, *pins], cwd=ROOT / project,
                         capture_output=True, text=True, check=True)
    lic = json.loads(res.stdout)
    return [(n, v, lic.get(n, "?")) for n, v in sorted(pins.items())]


def npm_rows() -> list[tuple[str, str, str]]:
    lock = json.loads((ROOT / "frontend" / "package-lock.json").read_text())
    rows = [(k.split("node_modules/")[-1], v.get("version", "?"), v.get("license", "?"))
            for k, v in lock["packages"].items() if k and not v.get("dev")]
    return sorted(rows)


def table(rows: list[tuple[str, str, str]]) -> str:
    return "| Package | Version | Licence |\n|---|---|---|\n" + "\n".join(f"| {n} | {v} | {l} |" for n, v, l in rows)


def main() -> None:
    parts = ["# Third-party libraries and tools\n",
             "Generated by `python3 scripts/third_party.py` from the lockfiles (production dependencies only). "
             "`?` = licence metadata not available locally (e.g. Windows-only packages). Infrastructure images: PostgreSQL, MinIO (`pgsty/minio` community build), Redis, SearXNG, nginx, Node, uv/Python base images.\n"]
    for p in PY_PROJECTS:
        if (ROOT / p / "uv.lock").exists():
            parts.append(f"\n## Python: `{p}`\n\n{table(python_rows(p))}\n")
    parts.append(f"\n## Frontend (npm)\n\n{table(npm_rows())}\n")
    (ROOT / "THIRD_PARTY.md").write_text("".join(parts), encoding="utf-8")
    print("THIRD_PARTY.md written")


if __name__ == "__main__":
    main()
